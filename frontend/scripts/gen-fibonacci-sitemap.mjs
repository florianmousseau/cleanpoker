/**
 * Writes the Fibonacci family into static/sitemap.xml, between its two
 * markers: the two reference pages and the 200 rank pages. The rest of the
 * sitemap is hand-written and left untouched. Run with
 * `node scripts/gen-fibonacci-sitemap.mjs` after changing the range.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SITEMAP = new URL('../static/sitemap.xml', import.meta.url);
const ORIGIN = 'https://pokeragile.com';
const FR = `${ORIGIN}/fr/suite-de-fibonacci`;
const EN = `${ORIGIN}/fibonacci-numbers`;
const START = '  <!-- fibonacci:start (generated by scripts/gen-fibonacci-sitemap.mjs) -->';
const END = '  <!-- fibonacci:end -->';

const entry = (loc, suffix, priority) => `  <url>
    <loc>${loc}</loc>
    <xhtml:link rel="alternate" hreflang="en" href="${EN}${suffix}"/>
    <xhtml:link rel="alternate" hreflang="fr" href="${FR}${suffix}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${EN}${suffix}"/>
    <changefreq>yearly</changefreq>
    <priority>${priority}</priority>
  </url>`;

const entries = [entry(EN, '', '0.8'), entry(FR, '', '0.8')];
for (let n = 1; n <= 100; n++) entries.push(entry(`${EN}/${n}`, `/${n}`, '0.5'), entry(`${FR}/${n}`, `/${n}`, '0.5'));
const block = [START, ...entries, END].join('\n');

const current = readFileSync(SITEMAP, 'utf8');
const from = current.indexOf(START);
const to = current.indexOf(END);
const next =
	from >= 0 && to > from
		? current.slice(0, from) + block + current.slice(to + END.length)
		: current.replace(/\n*<\/urlset>\s*$/, `\n\n${block}\n\n</urlset>\n`);
writeFileSync(SITEMAP, next);
console.log(`sitemap.xml: ${entries.length} Fibonacci entries`);
