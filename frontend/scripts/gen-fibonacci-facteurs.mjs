/**
 * Writes src/lib/fibonacci-facteurs.ts: the prime factorisation of F(1) to
 * F(100). Run with `node scripts/gen-fibonacci-facteurs.mjs`. The unit test
 * proves the result (each factor prime, product equal to F(n)), so this file
 * only has to find the factors, by trial division then Pollard's rho.
 */
import { writeFileSync } from 'node:fs';
import { estPremier, fib } from '../src/lib/fibonacci.ts';

const gcd = (a, b) => {
	while (b) [a, b] = [b, a % b];
	return a;
};
const rho = (n) => {
	for (let c = 1n; ; c++) {
		let x = 2n;
		let y = 2n;
		let d = 1n;
		while (d === 1n) {
			x = (x * x + c) % n;
			y = (y * y + c) % n;
			y = (y * y + c) % n;
			d = gcd(x > y ? x - y : y - x, n);
		}
		if (d !== n) return d;
	}
};
const factor = (n) => {
	const out = [];
	for (let p = 2n; p < 100000n && p * p <= n; p++) {
		while (n % p === 0n) {
			out.push(p);
			n /= p;
		}
	}
	const split = (m) => {
		if (m === 1n) return;
		if (estPremier(m)) return void out.push(m);
		const d = rho(m);
		split(d);
		split(m / d);
	};
	split(n);
	return out.sort((a, b) => (a < b ? -1 : 1));
};

const lignes = [];
for (let n = 1; n <= 100; n++) lignes.push(`\t'${factor(fib(n)).join(' ')}', // F(${n})`);
writeFileSync(
	new URL('../src/lib/fibonacci-facteurs.ts', import.meta.url),
	`/** Prime factors of F(1) to F(100), smallest first, repeated when squared. Generated by scripts/gen-fibonacci-facteurs.mjs. */
const FACTEURS = [
${lignes.join('\n')}
];

/** Return the prime factors of F(n) for n from 1 to 100; empty for F(1) = F(2) = 1. */
export function facteursPremiers(n: number): bigint[] {
	return FACTEURS[n - 1].split(' ').filter(Boolean).map(BigInt);
}
`
);
