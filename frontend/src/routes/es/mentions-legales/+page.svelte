    </p>

    <!-- ── Cookies ── -->
    <h2>Cookies</h2>
    <p>
      CleanPoker <strong>no utiliza ninguna cookie publicitaria ni ninguna herramienta que siga a un visitante</strong>.
    </p>
    <p>
      <strong>Ningún script mide su visita</strong>: no se carga ninguna herramienta de medición,
      no se deposita ninguna cookie con ese fin y no se escribe ningún identificador de visitante
      en su dispositivo. Como en cualquier sitio web, el proveedor que sirve estas páginas,
      Cloudflare, registra las solicitudes que responde, la página, el país, el navegador y la
      dirección IP en el momento de la solicitud, para entregar y proteger el servicio, en calidad de encargado del tratamiento. El servidor
      de juego en tiempo real, alojado en Fly.io, registra sus propias conexiones del mismo modo. Por eso
      nada aquí le pide su consentimiento: el consentimiento se aplica a la lectura o escritura de
      información en su dispositivo, y ninguna página hace ni lo uno ni lo otro.
    </p>
    <p>
      El servidor de juego mantiene dos contadores anónimos, el número de sesiones creadas y
      el número de llegadas. No contienen ningún identificador, ningún seudónimo y ningún
      nombre de sala, nada se escribe en disco, y vuelven a cero cada vez que el servidor se
      reinicia. Cualquiera puede leerlos en <code>/stats</code> del servidor de juego.
    </p>
    <p>
      El sitio deposita dos cookies funcionales en su navegador, para recordar su preferencia
      de idioma (<code>lang</code>) y su tema claro u oscuro (<code>theme</code>), conservadas
      un año. Son estrictamente funcionales, no contienen datos personales y no requieren
      consentimiento previo.
    </p>
    <p>
      Cloudflare puede depositar cookies técnicas de seguridad (<code>__cf_bm</code>) estrictamente
      necesarias para el buen funcionamiento del servicio (protección anti-DDoS). Estas cookies están exentas
      de consentimiento.
    </p>

