    <h2>O que a sala mostra na revelação</h2>
    <ul>
    <li>A média, a mediana, o mínimo e o máximo dos votos numéricos.</li>
    <li>O acordo: a percentagem de votos na carta mais escolhida.</li>
    <li>Uma barra por carta, com o respetivo número de votos.</li>
    </ul>
