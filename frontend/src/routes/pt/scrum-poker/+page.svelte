    <h2>Como decorre uma ronda de scrum poker</h2>
    <ol>
    <li>Uma pessoa <a href="/pt">cria uma sala no PokerAgile</a>, escolhe o baralho e envia a ligação à equipa.</li>
    <li>Cada pessoa abre a ligação e escreve um nome ou uma alcunha. Quem assiste sem votar entra como observador.</li>
    <li>O product owner lê a história de utilizador e responde às perguntas.</li>
    <li>Cada participante escolhe uma carta. A sala mostra quem já votou, mas não a carta escolhida.</li>
    <li>Quando todos tiverem votado, o botão «Revelar» mostra todas as cartas ao mesmo tempo. Uma opção revela-as automaticamente quando chega o último voto.</li>
    <li>A pessoa que votou mais baixo e a que votou mais alto explicam a sua carta. Depois, a equipa começa uma nova ronda ou guarda uma carta para a história.</li>
    </ol>

